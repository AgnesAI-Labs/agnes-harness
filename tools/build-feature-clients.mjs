import { access, readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { assertClientExternals, clientPlatformExternals } from './web-client-externals.mjs'

const root = fileURLToPath(new URL('../', import.meta.url))
const require = createRequire(join(root, 'packages/web/package.json'))
const { build } = require('esbuild')
const check = process.argv.includes('--check')
for (const [feature, presentation, suffix] of [
  ['goal-ui', 'goal-presentation', 'tsx'],
  ['interaction-ui', 'intelligent-ui-presentation', 'ts'],
  ['navigation-ui', '../../web/src/presentations/navigation', 'tsx'],
  ['conversation-ui', '../../web/src/presentations/conversation', 'tsx'],
]) {
  const outfile = join(root, `packages/package-manager/bundled-plugins/${feature}/src/client.js`)
  const result = await build({
    absWorkingDir: root,
    entryPoints: [`packages/web-conversation/src/${presentation}.${suffix}`],
    outfile,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2023',
    jsx: 'automatic',
    nodePaths: [join(root, 'packages/web/node_modules')],
    plugins: [clientPlatformExternals],
    minify: true,
    legalComments: 'eof',
    write: false,
    metafile: true,
  })
  assertClientExternals(result.metafile)
  const output = `// Generated by tools/build-feature-clients.mjs. Edit the source, then regenerate.\n${result.outputFiles[0].text}`
  if (check) {
    if ((await readFile(outfile, 'utf8')) !== output) throw new Error(`Stale feature bundle: ${outfile}`)
  } else await writeFile(outfile, output)
  const noticeFile = join(root, `packages/package-manager/bundled-plugins/${feature}/NOTICE`)
  const notice = await notices(result.metafile.inputs)
  if (check) {
    if ((await readFile(noticeFile, 'utf8')) !== notice) throw new Error(`Stale notice: ${feature}`)
  } else await writeFile(noticeFile, notice)
}

/** Preserve the exact notices of dependencies actually embedded into a browser asset. */
async function notices(inputs) {
  const packages = new Map()
  for (const file of Object.keys(inputs)) {
    if (!file.includes('node_modules/')) continue
    let directory = dirname(resolve(root, file))
    while (directory !== dirname(directory)) {
      try {
        const metadata = JSON.parse(await readFile(join(directory, 'package.json'), 'utf8'))
        if (metadata.name) {
          packages.set(metadata.name, { directory, metadata })
          break
        }
      } catch {}
      directory = dirname(directory)
    }
  }
  const blocks = []
  for (const [name, { directory, metadata }] of [...packages].sort(([a], [b]) => a.localeCompare(b))) {
    let license
    for (const candidate of ['LICENSE', 'LICENSE.md', 'license', 'LICENSE.txt']) {
      try {
        await access(join(directory, candidate))
        license = await readFile(join(directory, candidate), 'utf8')
        break
      } catch {}
    }
    if (!license) throw new Error(`Missing bundled license: ${name}`)
    blocks.push(
      `${name}@${metadata.version} (${metadata.license})\n${license
        .replace(/\r\n/g, '\n')
        .replace(/[ \t]+$/gm, '')
        .trim()}`,
    )
  }
  return (
    `Agnes Harness browser presentation. Project source is Apache-2.0.\nThe generated asset also includes these third-party components:\n\n${blocks.join('\n\n-----\n\n')}`.trimEnd() +
    '\n'
  )
}
