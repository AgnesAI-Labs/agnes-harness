import { access, readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { assertClientExternals, clientPlatformExternals } from './web-client-externals.mjs'

const require = createRequire(resolve('packages/web/package.json'))
const { build } = require('esbuild')
const check = process.argv.includes('--check')
for (const [feature, presentation, suffix] of [
  ['goal-ui', 'goal-presentation', 'tsx'],
  ['interaction-ui', 'intelligent-ui-presentation', 'ts'],
]) {
  const outfile = `packages/package-manager/bundled-plugins/${feature}/src/client.js`
  const result = await build({
    entryPoints: [`packages/web-conversation/src/${presentation}.${suffix}`],
    outfile,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2023',
    jsx: 'automatic',
    nodePaths: [resolve('packages/web/node_modules')],
    plugins: [clientPlatformExternals],
    minify: true,
    legalComments: 'eof',
    write: false,
    metafile: true,
  })
  assertClientExternals(result.metafile)
  const output = `// Generated by tools/build-feature-clients.mjs. Edit the source, then regenerate.\n${result.outputFiles[0].text}`
  if (check) {
    if ((await readFile(outfile, 'utf8')) !== output) throw new Error(`Stale feature bundle: ${outfile}`)
  } else await writeFile(outfile, output)
  const noticeFile = `packages/package-manager/bundled-plugins/${feature}/NOTICE`
  const notice = await notices(result.metafile.inputs)
  if (check) {
    if ((await readFile(noticeFile, 'utf8')) !== notice) throw new Error(`Stale notice: ${feature}`)
  } else await writeFile(noticeFile, notice)
}

// This optional plugin uses only platform externals; no vendor code is embedded.
{
  const root = 'packages/package-manager/bundled-plugins/context-doctor/src'
  const source = 'packages/context-doctor'
  const result = await build({
    entryPoints: [`${source}/src/client.tsx`],
    outfile: `${root}/client.js`,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2023',
    jsx: 'automatic',
    plugins: [clientPlatformExternals],
    write: false,
    minify: true,
    metafile: true,
  })
  assertClientExternals(result.metafile)
  for (const file of [
    'index.mjs',
    'package.json',
    'README.md',
    'README.zh-CN.md',
    'LICENSE',
    'src/metadata.mjs',
    'src/service.mjs',
    'src/locales.mjs',
    'src/agnes.client.json',
  ]) {
    let payload = await readFile(`${source}/${file}`, 'utf8')
    if (file.startsWith('README')) payload = payload.replaceAll('../../docs/', '../../../../docs/')
    const destination = `${root}/../${file}`
    if (check) {
      if ((await readFile(destination, 'utf8')) !== payload)
        throw new Error(`Stale context doctor payload: ${file}`)
    } else await writeFile(destination, payload)
  }
  const output = `// Generated by tools/build-feature-clients.mjs. Edit packages/context-doctor/src/client.tsx, then regenerate.\n${result.outputFiles[0].text}`
  if (check) {
    if ((await readFile(`${source}/src/client.js`, 'utf8')) !== output)
      throw new Error('Stale context doctor author bundle')
    if ((await readFile(`${root}/client.js`, 'utf8')) !== output)
      throw new Error('Stale context doctor bundle')
  } else {
    await writeFile(`${root}/client.js`, output)
    await writeFile(`${source}/src/client.js`, output)
  }
}

/** Preserve the exact notices of dependencies actually embedded into a browser asset. */
async function notices(inputs) {
  const packages = new Map()
  for (const file of Object.keys(inputs)) {
    if (!file.includes('node_modules/')) continue
    let directory = dirname(resolve(file))
    while (directory !== dirname(directory)) {
      try {
        const metadata = JSON.parse(await readFile(join(directory, 'package.json'), 'utf8'))
        if (metadata.name) {
          packages.set(metadata.name, { directory, metadata })
          break
        }
      } catch {}
      directory = dirname(directory)
    }
  }
  const blocks = []
  for (const [name, { directory, metadata }] of [...packages].sort(([a], [b]) => a.localeCompare(b))) {
    let license
    for (const candidate of ['LICENSE', 'LICENSE.md', 'license', 'LICENSE.txt']) {
      try {
        await access(join(directory, candidate))
        license = await readFile(join(directory, candidate), 'utf8')
        break
      } catch {}
    }
    if (!license) throw new Error(`Missing bundled license: ${name}`)
    blocks.push(
      `${name}@${metadata.version} (${metadata.license})\n${license
        .replace(/\r\n/g, '\n')
        .replace(/[ \t]+$/gm, '')
        .trim()}`,
    )
  }
  return (
    `Agnes Harness browser presentation. Project source is Apache-2.0.\nThe generated asset also includes these third-party components:\n\n${blocks.join('\n\n-----\n\n')}`.trimEnd() +
    '\n'
  )
}
