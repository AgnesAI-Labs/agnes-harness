export function buildSeed(now = Date.now()) {
  const d = (n) => new Date(now + n * DAY).toISOString()
  const hist = (steps, first) =>
    steps.map(([day, to, by, note], i) => ({
      at: d(day),
      by,
      from: i === 0 ? first : steps[i - 1][1],
      to,
      ...(note ? { note } : {}),
    }))

  const projects = PROJECTS.map(({ start, end, actualEnd, risks, ...p }) => ({
    ...p,
    plannedStart: d(start),
    plannedEnd: d(end),
    ...(actualEnd === undefined ? {} : { actualEnd: d(actualEnd) }),
    risks: risks.map(([id, title, level, owner, mitigation, status]) => ({
      id,
      title,
      level,
      owner,
      mitigation,
      status,
    })),
    live: false,
  }))

  const stages = STAGES.map(([projectId, stage, author, plannedEnd, steps, baseline]) => {
    const state = steps.at(-1)?.[1] ?? 'NOT_STARTED'
    return {
      id: `${projectId}/${stage}`,
      projectId,
      stage,
      state,
      author,
      plannedEnd: d(plannedEnd),
      ...(state === 'PASSED' ? { actualEnd: d(steps.at(-1)[0]) } : {}),
      ...(baseline ? { baseline: { id: baseline[0], at: d(baseline[1]), items: baseline[2] } } : {}),
      history: hist(steps, 'NOT_STARTED'),
    }
  })

  const gates = GATES.map(
    ([projectId, stage, n, approverRole, approver, decision, day, comment, findings]) => ({
      id: `GATE-${projectId}-${stage}-${n}`,
      stageId: `${projectId}/${stage}`,
      approverRole,
      ...(approver ? { approver } : {}),
      decision,
      findings: findings.map(([text, by, closedNote], i) => ({
        id: `F-${String(i + 1).padStart(2, '0')}`,
        text,
        by,
        closed: closedNote !== undefined,
        ...(closedNote ? { closedNote } : {}),
      })),
      ...(day === undefined ? {} : { decidedAt: d(day) }),
      ...(comment ? { comment } : {}),
    }),
  )

  const artifacts = ARTIFACTS.map(
    ([id, projectId, stage, kind, title, version, authorRole, status, day]) => ({
      id,
      projectId,
      stage,
      kind,
      title,
      version,
      authorRole,
      status,
      source: { type: 'seed', docId: id },
      updatedAt: d(day),
    }),
  )

  const reqs = []
  for (const [projectId, levels] of Object.entries(REQS)) {
    for (const [level, rows] of Object.entries(levels)) {
      for (const [id, title, text, parent] of rows) {
        reqs.push({
          id,
          projectId,
          level,
          title,
          text,
          parent,
          ...(SAFETY.has(id) ? { safety: true } : {}),
          verifiedBy: [],
          status: STATUS_OVERRIDE[id] ?? STATUS_DEFAULT[projectId][level],
        })
      }
    }
  }
  const byId = new Map(reqs.map((r) => [r.id, r]))
  for (const tc of reqs) if (tc.level === 'TC') for (const p of tc.parent) byId.get(p).verifiedBy.push(tc.id)

  const changes = CHANGES.map(({ steps, ccb, ...c }) => ({
    ...c,
    state: steps.at(-1)[1],
    ...(ccb ? { ccb: { members: ccb.members, decision: ccb.decision, at: d(ccb.day), note: ccb.note } } : {}),
    history: hist(steps, null),
  }))

  const defects = DEFECTS.map(
    ([id, projectId, severity, foundIn, testCase, req, title, owner, created, path]) => {
      const state = path.at(-1)?.[1] ?? 'NEW'
      return {
        id,
        projectId,
        title,
        severity,
        foundIn,
        ...(testCase ? { testCase } : {}),
        ...(req ? { req } : {}),
        state,
        owner,
        createdAt: d(created),
        ...(state === 'CLOSED' ? { closedAt: d(path.at(-1)[0]) } : {}),
        history: hist(
          [
            [created, 'NEW', projectId === P19 ? '测试工程师 宋雨' : '测试工程师 马骁', '登记'],
            ...path.map(([day, to]) => [day, to, owner]),
          ],
          null,
        ),
      }
    },
  )

  const testRuns = TEST_RUNS.map(([id, projectId, level, day, total, passed, failed, skipped, cov, log]) => ({
    id,
    projectId,
    level,
    at: d(day),
    total,
    passed,
    failed,
    skipped,
    ...(cov ? { coverage: { statement: cov[0], branch: cov[1] } } : {}),
    source: 'seed',
    log,
  }))

  return {
    schema: 2,
    revision: 1,
    projects,
    stages,
    gates,
    artifacts,
    reqs,
    changes,
    defects,
    testRuns,
    ...legacy(now),
  }
}

