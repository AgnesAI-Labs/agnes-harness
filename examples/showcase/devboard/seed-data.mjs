export function buildSeed(now = Date.now()) {
  const d = (n) => new Date(now + n * DAY).toISOString()
  const hist = (steps, first) =>
    steps.map(([day, to, by, note], i) => ({
      at: d(day),
      by,
      from: i === 0 ? first : steps[i - 1][1],
      to,
      ...(note ? { note } : {}),
    }))
  const roleOf = (by) => by.slice(0, by.lastIndexOf(' '))

  const projects = PROJECTS.map(({ start, end, actualEnd, risks, service, ...p }) => ({
    ...p,
    plannedStart: d(start),
    plannedEnd: d(end),
    ...(actualEnd === undefined ? {} : { actualEnd: d(actualEnd) }),
    ...(service
      ? { service: { ...service, warrantyEnd: d(service.warrantyEnd), deliveredAt: d(service.deliveredAt) } }
      : {}),
    risks: risks.map(([id, title, level, owner, mitigation, status]) => ({
      id,
      title,
      level,
      owner,
      mitigation,
      status,
    })),
    live: false,
  }))

  const stages = STAGES.map(([projectId, stage, plannedEnd, steps, baseline]) => {
    const state = steps.at(-1)?.[1] ?? 'NOT_STARTED'
    return {
      id: `${projectId}/${stage}`,
      projectId,
      stage,
      state,
      author: GATE_PROFILES[KIND[projectId]][stage].author,
      plannedEnd: d(plannedEnd),
      ...(state === 'PASSED' ? { actualEnd: d(steps.at(-1)[0]) } : {}),
      ...(baseline ? { baseline: { id: baseline[0], at: d(baseline[1]), items: baseline[2] } } : {}),
      history: hist(steps, 'NOT_STARTED'),
    }
  })

  const gates = GATES.map(([projectId, code, n, decision, day, comment, signatures, findings]) => {
    const profile = GATE_PROFILES[KIND[projectId]]
    const stage = Object.keys(profile).find((s) => profile[s].gates.some((g) => g.code === code))
    const gate = profile[stage].gates.find((g) => g.code === code)
    // Submitted by the stage's last move into review up to the decision.
    const submitted = stages
      .find((s) => s.id === `${projectId}/${stage}`)
      ?.history.filter((h) => h.to === 'IN_REVIEW' && (day === undefined || h.at <= d(day)))
      .at(-1)
    return {
      id: `GATE-${projectId}-${code}-${n}`,
      stageId: `${projectId}/${stage}`,
      code,
      name: gate.name,
      type: gate.type,
      approverRoles: [...gate.approverRoles],
      signatures: signatures.map(([by, signedDay, text]) => ({
        role: roleOf(by),
        by,
        at: d(signedDay),
        comment: text,
      })),
      decision,
      findings: findings.map(([text, by, closedNote], i) => ({
        id: `F-${String(i + 1).padStart(2, '0')}`,
        text,
        by,
        closed: closedNote !== undefined,
        ...(closedNote ? { closedNote } : {}),
      })),
      ...(submitted ? { submittedAt: submitted.at, submittedBy: submitted.by } : {}),
      ...(day === undefined ? {} : { decidedAt: d(day) }),
      ...(comment ? { comment } : {}),
    }
  })

  const artifacts = ARTIFACTS.map(
    ([id, projectId, stage, kind, title, version, authorRole, status, day]) => ({
      id,
      projectId,
      stage,
      kind,
      title,
      version,
      authorRole,
      status,
      source: { type: 'seed', docId: id },
      updatedAt: d(day),
    }),
  )

  const clause = new Map(CLAUSES.map(([id, ...rest]) => [id, rest]))
  const design = new Map(DESX.map(([id, ...rest]) => [id, rest]))
  const DISCIPLINE = { SWR: 'SW', MER: 'MECH', EER: 'ELEC' }
  const reqs = []
  for (const projectId of [P42, P08, P19, P11]) {
    for (const level of ['CUS', 'SYS', 'SWR', 'DES', 'TC']) {
      const rows = [...(REQS[projectId]?.[level] ?? []), ...(REQS_V3[projectId]?.[level] ?? [])]
      for (const [id, title, text, parent] of rows) {
        const [cl, compliance, responseNote] = level === 'CUS' ? clause.get(id) : []
        const [dDiscipline, partNo, drawingNo, module] = level === 'DES' ? design.get(id) : []
        reqs.push({
          id,
          projectId,
          level,
          title,
          text,
          parent,
          ...(SAFETY.has(id) ? { safety: true } : {}),
          ...(level === 'SWR' ? { discipline: DISCIPLINE[id.slice(0, 3)] } : {}),
          ...(level === 'DES' ? { discipline: dDiscipline } : {}),
          ...(partNo ? { partNo, drawingNo } : {}),
          ...(module ? { module } : {}),
          ...(level === 'CUS' ? { clause: cl, compliance, ...(responseNote ? { responseNote } : {}) } : {}),
          verifiedBy: [],
          status: STATUS_OVERRIDE[id] ?? STATUS_DEFAULT[projectId][level],
        })
      }
    }
  }
  const byId = new Map(reqs.map((r) => [r.id, r]))
  for (const tc of reqs) if (tc.level === 'TC') for (const p of tc.parent) byId.get(p).verifiedBy.push(tc.id)
  // An SWR is VERIFIED exactly when all its TCs are, so the cases under a verified SWR passed too.
  for (const tc of reqs)
    if (
      tc.level === 'TC' &&
      tc.parent.some((p) => byId.get(p).level === 'SWR' && byId.get(p).status === 'VERIFIED')
    )
      tc.status = 'VERIFIED'

  const changes = CHANGES.map(({ steps, ccb, verification, ...c }) => ({
    ...c,
    state: steps.at(-1)[1],
    ...(ccb ? { ccb: { members: ccb.members, decision: ccb.decision, at: d(ccb.day), note: ccb.note } } : {}),
    ...(verification
      ? {
          verification: {
            result: verification.result,
            by: verification.by,
            at: d(verification.day),
            ...(verification.trialId ? { trialId: verification.trialId } : {}),
          },
        }
      : {}),
    history: hist(steps, null),
  }))

  const defects = DEFECTS.map(
    ([id, projectId, severity, foundIn, testCase, req, title, owner, created, path]) => {
      const state = path.at(-1)?.[1] ?? 'NEW'
      return {
        id,
        projectId,
        title,
        severity,
        foundIn,
        ...(testCase ? { testCase } : {}),
        ...(req ? { req } : {}),
        state,
        owner,
        createdAt: d(created),
        ...(state === 'CLOSED' ? { closedAt: d(path.at(-1)[0]) } : {}),
        history: hist(
          [
            [created, 'NEW', projectId === P19 ? '验证工程师 宋雨' : '验证工程师 马骁', '登记'],
            ...path.map(([day, to]) => [day, to, owner]),
          ],
          null,
        ),
      }
    },
  )

  const testRuns = TEST_RUNS.map(([id, projectId, level, day, total, passed, failed, skipped, cov, log]) => ({
    id,
    projectId,
    level,
    at: d(day),
    total,
    passed,
    failed,
    skipped,
    ...(cov ? { coverage: { statement: cov[0], branch: cov[1] } } : {}),
    source: 'seed',
    log,
  }))

  const trials = TRIALS.map(
    ([
      id,
      projectId,
      type,
      title,
      standard,
      sample,
      lab,
      witness,
      planned,
      at,
      reportNo,
      result,
      deviations,
      verifies,
      changeId,
      path,
    ]) => ({
      id,
      projectId,
      type,
      title,
      standard,
      sample,
      lab,
      ...(witness ? { witness } : {}),
      plannedAt: d(planned),
      ...(at === undefined ? {} : { at: d(at) }),
      ...(reportNo ? { reportNo } : {}),
      result,
      deviations,
      verifies,
      ...(changeId ? { changeId } : {}),
      state: path.at(-1)[1],
      history: hist(
        path.map(([day, to, note]) => [
          day,
          to,
          to === 'APPROVED' ? '质量工程师 韩雪' : '验证工程师 马骁',
          note,
        ]),
        null,
      ),
    }),
  )

  // Faults are numbered in detection order, 8 apart, so the latest is FA-2026-0412.
  const GROUP_PROBLEM = { C1: 'QP-2026-003', C2: 'QP-2026-007' }
  const DEFAULT_BY = { DISPATCHED: '诊断工程师 钟灵', HANDLED: '客服工程师 贺平', CLOSED: '诊断工程师 钟灵' }
  const SOURCE_BY = { PHM: 'PHM 平台', 客服: '客服工程师 贺平', 主机厂: '客户代表 方卫东' }
  const faults = FAULT_ROWS.map((row, i) => ({ row, i }))
    .sort((a, b) => a.row[8] - b.row[8] || a.i - b.i)
    .map(({ row }, n) => {
      const [group, source, signal, train, car, door, score, detail, day, path] = row
      return {
        id: `FA-2026-${String(100 + n * 8).padStart(4, '0')}`,
        projectId: P11,
        source,
        signal,
        train,
        car,
        door,
        ...(score === undefined ? {} : { healthScore: score }),
        detail,
        detectedAt: d(day),
        state: path.at(-1)?.[1] ?? 'NEW',
        ...(GROUP_PROBLEM[group] ? { problemId: GROUP_PROBLEM[group] } : {}),
        history: hist(
          [
            [day, 'NEW', SOURCE_BY[source], source === 'PHM' ? 'PHM 平台自动上报' : '登记'],
            ...path.map(([pd, to, note]) => [pd, to, DEFAULT_BY[to], note]),
          ],
          null,
        ),
      }
    })

  const problems = PROBLEMS.map(
    ([id, title, _group, severity, owner, steps, rootCause, containment, changeId, path]) => ({
      id,
      projectId: P11,
      title,
      faultIds: faults.filter((f) => f.problemId === id).map((f) => f.id),
      severity,
      steps: Object.fromEntries(
        Array.from({ length: 8 }, (_, i) => [
          `D${i + 1}`,
          steps[i] ? { done: true, text: steps[i] } : { done: false },
        ]),
      ),
      ...(rootCause ? { rootCause } : {}),
      ...(containment ? { containment } : {}),
      ...(changeId ? { changeId } : {}),
      state: path.at(-1)[1],
      owner,
      history: hist(
        path.map(([day, to, note]) => [day, to, owner, note]),
        null,
      ),
    }),
  )

  const subjects = { artifact: artifacts, change: changes, problem: problems, trial: trials }
  const approvals = APPROVALS.map(([id, template, type, subjectId, initiator, start, events]) => {
    const subject = subjects[type].find((x) => x.id === subjectId)
    const flow = newFlow({
      id,
      projectId: subject.projectId,
      template,
      subject: { type, id: subjectId },
      title: `${TEMPLATE_NAME[template]}：${subjectId} ${subject.title}`,
      initiator: { role: roleOf(initiator), by: initiator },
      now: now + start * DAY,
    })
    for (const [day, by, action, extra] of events) act(flow, { by, action, ...extra }, now + day * DAY)
    return flow
  })

  const items = ITEMS.map(([id, name, discipline, lru]) => ({ id, projectId: P11, name, discipline, lru }))
  const configBaselines = CONFIG_BASELINES.map(([type, n, day, revIndex, note]) => ({
    id: `CB-${P11}-${type}-${String(n).padStart(2, '0')}`,
    projectId: P11,
    type,
    revs: Object.fromEntries(ITEMS.map(([id, , , , revs]) => [id, revs[revIndex]])),
    at: d(day),
    note,
  }))

  return {
    schema: 4,
    revision: 1,
    projects,
    stages,
    gates,
    artifacts,
    reqs,
    changes,
    defects,
    testRuns,
    trials,
    faults,
    problems,
    items,
    configBaselines,
    approvals,
    ...legacy(now),
  }
}

