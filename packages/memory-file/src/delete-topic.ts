import { randomUUID } from 'node:crypto'
import { type BigIntStats, linkSync, lstatSync, readFileSync, renameSync, rmSync, unlinkSync } from 'node:fs'
import { join } from 'node:path'
import { setTimeout as delay } from 'node:timers/promises'
import { syncDirectorySync } from '@agnes/system-node'
import { fault } from './content.js'
import { isMemoryName, missing, safe } from './paths.js'
import type { MemoryStore } from './store.js'

const intentName = 'delete-intent.json'
const pending = new Map<string, string>()
export const provisionalTopic = (root: string) => pending.get(root)

export async function retryBusy(action: () => void): Promise<void> {
  const deadline = performance.now() + 1000
  for (;;) {
    try {
      return action()
    } catch (error) {
      if (
        !['EBUSY', 'EPERM', 'EACCES'].includes((error as NodeJS.ErrnoException).code ?? '') ||
        performance.now() >= deadline
      )
        throw error
      await delay(10)
    }
  }
}

export function hasDeleteIntent(root: string): boolean {
  return !!lstatSync(join(root, intentName), { throwIfNoEntry: false })
}

// Retain a reclaimed name and quarantine the tombstone in place. A matching inode means
// recovery already linked it back and was interrupted before removing the temporary name.
function restore(original: string, tombstone: string) {
  try {
    linkSync(tombstone, original)
  } catch (error) {
    if (missing(error)) return
    if ((error as NodeJS.ErrnoException).code !== 'EEXIST') throw error
    const from = lstatSync(tombstone, { bigint: true })
    const to = lstatSync(original, { bigint: true })
    if (from.dev !== to.dev || from.ino !== to.ino) return
  }
  unlinkSync(tombstone)
}

function finish(root: string) {
  syncDirectorySync(root)
  rmSync(join(root, intentName), { force: true })
  syncDirectorySync(root)
}

/** Called only with the exclusive store lock. Accept only names generated by unlinkTopic. */
export function recoverTopic(store: MemoryStore) {
  const intent = join(store.root, intentName)
  safe(store.protectedRoot, intent)
  const stat = lstatSync(intent, { throwIfNoEntry: false })
  if (!stat) return syncDirectorySync(store.root)
  if (!stat.isFile() || stat.size > 256) throw fault('MEMORY_INVALID_METADATA')
  const { path, id } = JSON.parse(readFileSync(intent, 'utf8'))
  if (
    typeof path !== 'string' ||
    !isMemoryName(path) ||
    path.toLowerCase() === 'memory.md' ||
    typeof id !== 'string' ||
    !/^[0-9a-f]{8}(-[0-9a-f]{4}){3}-[0-9a-f]{12}$/u.test(id)
  )
    throw fault('MEMORY_INVALID_METADATA')
  restore(join(store.root, path), join(store.root, `${path}.${id}.del.tmp`))
  finish(store.root)
}

export async function unlinkTopic(
  store: MemoryStore,
  leaf: string,
  matches: (tombstone: string, identity: BigIntStats) => boolean,
  assertActive: () => void,
  prune: () => void,
): Promise<void> {
  const id = randomUUID()
  const original = join(store.root, leaf)
  const tombstone = `${original}.${id}.del.tmp`
  pending.set(store.root, leaf)
  try {
    store.atomic(join(store.root, intentName), JSON.stringify({ path: leaf, id }))
    try {
      await retryBusy(() => {
        assertActive()
        renameSync(original, tombstone)
      })
      await retryBusy(() => {
        assertActive()
        const entry = lstatSync(tombstone, { bigint: true })
        if (!entry.isFile() || entry.nlink !== 1n || !matches(tombstone, entry))
          throw fault('MEMORY_CONFLICT')
        assertActive()
        prune()
        unlinkSync(tombstone)
      })
    } catch (error) {
      await retryBusy(() => recoverTopic(store))
      throw error
    }
  } finally {
    pending.delete(store.root)
  }
}

export const finishTopicDeletion = (root: string) => retryBusy(() => finish(root))
