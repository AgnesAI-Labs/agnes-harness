import { describe, expect, it } from 'vitest'
import { splitShellCommand } from '../src/command-table/split.js'

describe('splitShellCommand', () => {
  it.each<[string, string[][]]>([
    ['git status', [['git', 'status']]],
    ['  git   status  ', [['git', 'status']]],
    [
      'git status && git diff',
      [
        ['git', 'status'],
        ['git', 'diff'],
      ],
    ],
    ['a || b ; c | d', [['a'], ['b'], ['c'], ['d']]],
    ['ls;', [['ls']]],
    ['echo \'a b\' "c d"', [['echo', 'a b', 'c d']]],
    ['echo \'a\'"b"c', [['echo', 'abc']]],
    ["echo '$HOME `x` * > <'", [['echo', '$HOME `x` * > <']]],
    ['echo "a && b"', [['echo', 'a && b']]],
    ['echo a#b', [['echo', 'a#b']]],
    ["echo ''", [['echo', '']]],
    ['make a=b', [['make', 'a=b']]],
    ["echo '~' x~y", [['echo', '~', 'x~y']]],
    ['rm -rf ./build', [['rm', '-rf', './build']]],
  ])('splits %j', (input, expected) => {
    expect(splitShellCommand(input)).toEqual(expected)
  })

  it.each([
    '',
    '   ',
    ';',
    'a &&',
    'a ||',
    'a |',
    '&& a',
    'a && && b',
    'a ;; b',
    'echo $(id)',
    'echo `id`',
    'echo $HOME',
    'echo "$HOME"',
    'echo "`id`"',
    'echo "a\\"b"',
    'echo a > f',
    'echo a >> f',
    'cat < f',
    'cat <<EOF',
    '(a)',
    '{ a; }',
    'a &',
    'a & b',
    'a |& b',
    'ls *.ts',
    'ls a?',
    'ls [a]',
    'echo a\\ b',
    'echo a\nb',
    'echo a\rb',
    "echo 'abc",
    'echo "abc',
    '# comment',
    'a # comment',
    '! a',
    ':(){ :|:& };:',
    'echo \u201chi\u201d',
    'echo \u2018hi\u2019',
    'git status \u201e',
    'echo caf\u00e9',
    'ls \u00a0x',
    'ls ~',
    'ls ~/x',
    '=ls',
    'echo a^b',
    'echo 50%',
    'FOO=bar make test',
    'GIT_SSH_COMMAND=x git push',
    'git status && FOO=1 ls',
    'if true; then ls; fi',
    'while true; do ls; done',
    'for x in a; do ls; done',
    'case a in esac',
    'time ls',
    'exec ls',
    'eval ls',
    'source f',
    '. f',
    'command ls',
    'builtin ls',
    'ls && eval ls',
    'select x',
    'function f',
    'coproc ls',
    '[[ a ]]',
    'git status; exec ls',
  ])('is opaque: %j', (input) => {
    expect(splitShellCommand(input)).toBeUndefined()
  })
})
