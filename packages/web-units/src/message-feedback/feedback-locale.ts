import { createCatalogTranslator, type LocaleCatalog } from '@agnes/web-ui'
import { useSyncExternalStore } from 'react'

const language = () => (document.documentElement.lang === 'zh-CN' ? ('zh-CN' as const) : ('en' as const))
const subscribe = (listener: () => void) => {
  const observer = new MutationObserver(listener)
  observer.observe(document.documentElement, { attributes: true, attributeFilter: ['lang'] })
  return () => observer.disconnect()
}
/** Timeline and workbench use separate React roots; share the document's live locale preference. */
export function useFeedbackText() {
  const locale = useSyncExternalStore(subscribe, language, () => 'en' as const)
  return { t: createCatalogTranslator(feedbackCatalog, locale) }
}
