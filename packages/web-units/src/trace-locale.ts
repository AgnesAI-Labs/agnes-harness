export const traceCatalog = { en: { ...en }, 'zh-CN': { ...zh } }
export type TraceMessageKey = keyof typeof en

export function traceLocale(): 'en' | 'zh-CN' {
  if (typeof document !== 'undefined' && document.documentElement?.lang === 'zh-CN') return 'zh-CN'
  return 'en'
}

export function traceText(
  key: TraceMessageKey,
  vars?: Readonly<Record<string, string | number>>,
  locale: 'en' | 'zh-CN' = traceLocale(),
): string {
  const template = traceCatalog[locale][key] ?? traceCatalog.en[key]
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.hasOwn(vars, name) ? String(vars[name]) : match,
  )
}
