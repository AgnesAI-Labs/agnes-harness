import type { SlotKind, SlotScope, SlotSpec } from '@agnes/web-slots'

/**
 * Version of the independent DSH-aligned browser slot contract.
 *
 * This catalog is deliberately separate from the protocol data-slot names and
 * from the set of slots currently mounted by the Agnes shell. A name being
 * known here only means that its contract is understood; the shell must still
 * declare a live owner before a contribution can register into it.
 */
export const DSH_SLOT_CATALOG_VERSION = 'dsh-client-slots/v1' as const

export interface DshSlotDefinition {
  readonly key: string
  readonly kind: SlotKind
  readonly scope: SlotScope
  readonly parent: string | undefined
  readonly public: boolean
  readonly hostOnly: boolean
  readonly owner: string
  readonly fallback: 'host' | 'empty' | 'chain'
}

const definition = (
  key: string,
  kind: SlotKind,
  scope: SlotScope,
  parent: string | undefined,
  owner: string,
  fallback: DshSlotDefinition['fallback'] = kind === 'chain' ? 'chain' : 'empty',
): DshSlotDefinition => ({
  key,
  kind,
  scope,
  parent,
  public: key !== 'root',
  hostOnly: key === 'root',
  owner,
  fallback,
})

