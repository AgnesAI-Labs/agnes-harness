const catalogByName = new Map(DSH_SLOT_CATALOG.map((slot) => [slot.key, slot]))

export function getDshSlotDefinition(name: string): DshSlotDefinition | undefined {
  return catalogByName.get(name)
}

export function isKnownDshSlot(name: string): name is DshSlotName {
  return catalogByName.has(name)
}

export function isPublicDshSlot(name: string): name is DshSlotName {
  return catalogByName.get(name)?.public === true
}

export function isRuntimeSupportedDshSlot(name: string): boolean {
  return DSH_RUNTIME_SUPPORTED_SLOT_NAMES.includes(name)
}

export function dshSlotSpec(name: string): SlotSpec | undefined {
  const slot = catalogByName.get(name)
  return slot === undefined ? undefined : { kind: slot.kind, scope: slot.scope }
}

