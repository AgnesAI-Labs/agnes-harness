    'agh agents [--all] [--json]',
    'agh credentials [list] | rename <id> <name...> | delete <id> [--yes [--force]] [--json]',
    'agh export <id> [--format agnes|sharegpt|claude-code] [--html] [--raw] [-o|--out <file>]',
