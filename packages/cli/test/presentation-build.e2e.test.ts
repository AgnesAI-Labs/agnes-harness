import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { expect, it } from 'vitest'
import { buildPresentations, presentationRoot } from '../../../tools/presentation-build.mjs'

it.each(['local', 'sea', 'release'] as const)(
  'refuses a self-consistent forged presentation cache in the real %s packaging command',
  async (kind) => {
    await buildPresentations()
    const source = join(presentationRoot, 'packages/package-manager/bundled-plugins/goal-ui')
    const clientPath = join(source, 'src/client.js')
    const recordPath = join(source, 'client-build.json')
    const client = await readFile(clientPath)
    const record = await readFile(recordPath)
    const output = await mkdtemp(join(tmpdir(), 'agh-presentation-poison-'))
    try {
      const poisoned = Buffer.concat([client, Buffer.from('\n// forged generated output\n')])
      const forged = JSON.parse(record.toString())
      forged.bytes = poisoned.length
      forged.files['src/client.js'] = `sha256-${createHash('sha256').update(poisoned).digest('hex')}`
      await writeFile(clientPath, poisoned)
      await writeFile(recordPath, `${JSON.stringify(forged, null, 2)}\n`)
      const args =
        kind === 'release'
          ? ['release:pack', '--output', output]
          : ['--filter', '@agnes/cli', `build:${kind}`]
      const result = spawnSync(process.execPath, ['tools/toolchain/run.mjs', ...args], {
        cwd: presentationRoot,
        encoding: 'utf8',
        timeout: 120_000,
        maxBuffer: 16 * 1024 * 1024,
      })
      const diagnostic = `${result.stdout}\n${result.stderr}`
      expect(result.error, diagnostic).toBeUndefined()
      expect(result.status, diagnostic).not.toBe(0)
      expect(diagnostic).toContain('Stale presentation build: goal-ui')
      // Refusal must not silently replace the evidence with regenerated bytes.
      expect(await readFile(clientPath)).toEqual(poisoned)
      expect(JSON.parse(await readFile(recordPath, 'utf8')).inputHash).toBe(forged.inputHash)
    } finally {
      await writeFile(clientPath, client)
      await writeFile(recordPath, record)
      await rm(output, { recursive: true, force: true })
    }
  },
  150_000,
)
