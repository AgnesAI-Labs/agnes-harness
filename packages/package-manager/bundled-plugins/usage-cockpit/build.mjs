import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { assertClientExternals, clientPlatformExternals } from '../../../../tools/web-client-externals.mjs'

const require = createRequire(new URL('../../../web/package.json', import.meta.url))
const { build } = require('esbuild')
const outfile = fileURLToPath(new URL('src/generated/client.js', import.meta.url))
const result = await build({
  entryPoints: [fileURLToPath(new URL('src/client.tsx', import.meta.url))],
  outfile,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2023',
  jsx: 'automatic',
  plugins: [clientPlatformExternals],
  metafile: true,
  write: false,
})
assertClientExternals(result.metafile)
const output = `// Generated by packages/package-manager/bundled-plugins/usage-cockpit/build.mjs. Edit TypeScript, then regenerate.\n${result.outputFiles[0].text}`
if (process.argv.includes('--check')) {
  if ((await readFile(outfile, 'utf8')) !== output) throw new Error('Stale usage cockpit client')
} else {
  await mkdir(dirname(outfile), { recursive: true })
  await writeFile(outfile, output)
}
