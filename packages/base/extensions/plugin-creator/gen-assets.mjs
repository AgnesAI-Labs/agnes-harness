import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'

const templatesRoot = new URL('../../../../templates/', import.meta.url)
const scaffold = await readFile(new URL('create-agh-plugin.mjs', templatesRoot), 'utf8')
const templateNames = ['tool', 'tool-with-panel', 'mcp-skills', 'model-adapter', 'loop']
const files = {}
async function collect(url, prefix) {
  // Filesystem enumeration differs across platforms; generated assets need one byte order.
  const entries = (await readdir(url, { withFileTypes: true })).sort((a, b) => {
    if (a.name === b.name) return 0
    return a.name < b.name ? -1 : 1
  })
  for (const entry of entries) {
    const path = `${prefix}/${entry.name}`
    if (entry.isDirectory()) await collect(new URL(`${entry.name}/`, url), path)
    else files[path] = await readFile(new URL(entry.name, url), 'utf8')
  }
}
for (const name of templateNames) await collect(new URL(`${name}/`, templatesRoot), name)
const scaffoldSource = scaffold
  .slice(scaffold.indexOf('export async function scaffold'), scaffold.indexOf('\nif (process.argv[1]'))
  .replace('export async function', 'async function')
const skill = await readFile(new URL('skills/plugin-creator/SKILL.md', import.meta.url), 'utf8')
const { authoringGuidance, authoringContextGuidance, toolSafetyGuidance } = await import(
  '../../../package-manager/bundled-plugins/plugin-helper/src/authoring.mjs'
)
// The helper exposes the existing panel scaffold, generated from exactly the same files.
const panelFiles = Object.entries(files)
  .filter(([path]) => path.startsWith('tool-with-panel/'))
  .map(([path, content]) => ({
    path: path.slice('tool-with-panel/'.length),
    content: content
      .replaceAll('__PACKAGE_NAME__', 'my-agh-plugin')
      .replaceAll('__TOOL_NAME__', 'plugin_my_agh_plugin')
      .replaceAll('__SERVICE_NAME__', 'pluginmyaghplugin')
      .replaceAll('__SKILL_NAME__', 'my-agh-plugin')
      .replaceAll('__SETUP_GUIDE__', 'Test the final candidate hash and submit human review.')
      .replaceAll('../dist/index.js', '../src/index.ts'),
  }))
const panelManifest = panelFiles.find((file) => file.path === 'package.json')
const panelPackage = JSON.parse(panelManifest.content)
panelPackage.exports = './src/index.ts'
panelPackage.files = ['src', 'client', 'skills', 'mcp.json']
delete panelPackage.dependencies
delete panelPackage.devDependencies
panelPackage.scripts = { test: 'node --test test/*.test.mjs' }
panelManifest.content = `${JSON.stringify(panelPackage, null, 2)}\n`
const panelTarget = new URL(
  '../../../package-manager/bundled-plugins/plugin-helper/src/panel.generated.mjs',
  import.meta.url,
)
const panelOutput = `// Generated from templates/tool-with-panel by plugin-creator/gen-assets.mjs; do not edit.\n// biome-ignore-all lint/suspicious/noTemplateCurlyInString: canonical template source contains literal placeholders\n// biome-ignore format: preserve generator output\nexport const panelFiles = ${JSON.stringify(panelFiles, null, 2)}\n`
if (process.argv.includes('--check')) {
  if ((await readFile(panelTarget, 'utf8')) !== panelOutput) throw new Error('Helper panel template is stale')
} else await writeFile(panelTarget, panelOutput)
const data = {
  templateNames,
  files,
  scaffoldSource,
  skill,
  authoringGuidance,
  authoringContextGuidance,
  toolSafetyGuidance,
}
const output = `// Generated by gen-assets.mjs from create-agh-plugin, templates and the bundled Skill.\n// biome-ignore-all lint/suspicious/noTemplateCurlyInString: canonical template source contains literal placeholders
// biome-ignore format: preserve the generator output\nexport const creatorAssets = ${JSON.stringify(data, null, 2)} as const\n`
await mkdir(new URL('src/generated/', import.meta.url), { recursive: true })
const target = new URL('src/generated/assets.ts', import.meta.url)
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')) !== output)
    throw new Error('Plugin creator assets are stale; run gen-assets.mjs')
} else await writeFile(target, output)
