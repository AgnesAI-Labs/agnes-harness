const DICT: Record<Locale, Record<ExtendedKey, string>> = {
  en: {
    ...BASE.en,
    ...CONTROL_DICT.en,
    ...TERMINAL_DICT.en,
    ...TOOLS_DICT.en,
    ...KEYS_DICT.en,
    ...UNDO_DICT.en,
  },
  'zh-CN': {
    ...BASE['zh-CN'],
    ...CONTROL_DICT['zh-CN'],
    ...TERMINAL_DICT['zh-CN'],
    ...TOOLS_DICT['zh-CN'],
    ...KEYS_DICT['zh-CN'],
    ...UNDO_DICT['zh-CN'],
  },
}

export function tt(
  key: ExtendedKey,
  locale: string,
  vars: Readonly<Record<string, string | number>> = {},
): string {
  const dictionary = DICT[(LOCALES as readonly string[]).includes(locale) ? (locale as Locale) : 'en']
  return dictionary[key].replace(/\{(\w+)\}/g, (_match, name: string) => String(vars[name] ?? `{${name}}`))
}

